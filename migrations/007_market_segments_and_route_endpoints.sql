INSERT INTO company_cnaes(company_id,cnpj,primary_cnae,primary_description,source_name,source_updated_at)
SELECT customer_id,normalized_cnpj,primary_cnae,primary_description,'erp_existing',source_updated_at
FROM (
  SELECT DISTINCT ON (regexp_replace(customer.cnpj,'\D','','g'))
    customer.id AS customer_id,regexp_replace(customer.cnpj,'\D','','g') AS normalized_cnpj,
    customer.primary_cnae,customer.primary_cnae_description AS primary_description,
    coalesce(customer.cnae_enriched_at,now()) AS source_updated_at
  FROM erp_customers customer
  WHERE customer.primary_cnae ~ '^[0-9]{7}$'
    AND length(regexp_replace(customer.cnpj,'\D','','g'))=14
  ORDER BY regexp_replace(customer.cnpj,'\D','','g'),customer.id
) existing
ON CONFLICT(company_id) DO NOTHING;

