CREATE TABLE IF NOT EXISTS macro_segments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS micro_segments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  macro_segment_id bigint NOT NULL REFERENCES macro_segments(id),
  name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (macro_segment_id, name)
);

CREATE TABLE IF NOT EXISTS segment_reference_companies (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  micro_segment_id bigint NOT NULL REFERENCES micro_segments(id),
  reference_name text NOT NULL,
  source_name text NOT NULL DEFAULT 'MACRO SEGMENBTAÇÃO DE CLIENTES.xlsx',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (micro_segment_id, reference_name)
);

CREATE TABLE IF NOT EXISTS company_cnaes (
  company_id uuid PRIMARY KEY REFERENCES erp_customers(id) ON DELETE CASCADE,
  cnpj text NOT NULL UNIQUE CHECK (cnpj ~ '^[0-9]{14}$'),
  primary_cnae text NOT NULL CHECK (primary_cnae ~ '^[0-9]{7}$'),
  secondary_cnaes text[] NOT NULL DEFAULT '{}',
  primary_description text,
  source_name text NOT NULL DEFAULT 'BrasilAPI/CNPJ',
  source_updated_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS company_cnaes_primary_idx ON company_cnaes(primary_cnae);
CREATE INDEX IF NOT EXISTS company_cnaes_secondary_gin_idx ON company_cnaes USING gin(secondary_cnaes);

CREATE TABLE IF NOT EXISTS cnae_segment_mappings (
  cnae_fiscal text NOT NULL CHECK (cnae_fiscal ~ '^[0-9]{7}$'),
  macro_segment_id bigint NOT NULL REFERENCES macro_segments(id),
  micro_segment_id bigint NOT NULL REFERENCES micro_segments(id),
  reference_company_id bigint REFERENCES segment_reference_companies(id),
  source_customer_id uuid REFERENCES erp_customers(id),
  review_status text NOT NULL DEFAULT 'pending'
    CHECK (review_status IN ('pending', 'approved', 'rejected')),
  source_name text NOT NULL,
  reviewed_by text,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (cnae_fiscal, micro_segment_id)
);
CREATE INDEX IF NOT EXISTS cnae_segment_mappings_review_idx
  ON cnae_segment_mappings(cnae_fiscal, review_status);
CREATE INDEX IF NOT EXISTS cnae_segment_mappings_seed_idx
  ON cnae_segment_mappings(source_customer_id, review_status);

